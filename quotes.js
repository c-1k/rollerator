let lastLine = "";

export function pickHortQuote(kind, value) {
  const pool =
    kind === "d20" && value === 20
      ? HORT.high
      : kind === "d20" && value === 1
        ? HORT.low
        : HORT.all;
  let pick = pool[Math.floor(Math.random() * pool.length)];
  if (pool.length > 1) {
    let guard = 0;
    while (pick.line === lastLine && guard < 8) {
      pick = pool[Math.floor(Math.random() * pool.length)];
      guard += 1;
    }
  }
  lastLine = pick.line;
  return pick;
}
